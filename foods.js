function chooseGroup(name, category, kcal, protein, carbs, fat) {
  if (GROUP_OVERRIDE[name]) return GROUP_OVERRIDE[name];
  const n = norm(name);
  if (category === 'Δημητριακά') return 'starch';
  if (category === 'Φρούτα') return 'fruit';
  if (category === 'Λαχανικά') return 'vegetable';
  if (category === 'Λίπη & ξηροί καρποί') return 'fat';
  if (category === 'Σνακ & γλυκά') return 'starch';
  if (category === 'Φυτικά') return meatGroup(protein, fat);
  if (category === 'Κρέας' || category === 'Ψάρι') return meatGroup(protein, fat);
  if (category === 'Γαλακτοκομικά') {
    if (/αυγο|ασπραδι/.test(n)) return meatGroup(protein, fat);
    if (/κρεμα γαλακτοσ/.test(n)) return 'fat';
    if (CHEESE.test(n)) return meatGroup(protein, fat);
    return 'milk';
  }
  if (category === 'Όσπρια') {
    if (/φασολακια/.test(n)) return 'vegetable';
    return 'starch';
  }
  if (category === 'Ροφήματα') {
    if (kcal < 15 && carbs < 2) return 'free';
    return 'starch';
  }
  if (category === 'Παραδοσιακά') {
    if (carbs >= 8) return 'starch';
    if (fat >= 8) return 'fat';
    return 'starch';
  }
  return carbs >= 10 ? 'starch' : 'free';
}

function legumeSecondary(name, category, group) {
  if (group !== 'starch') return false;
  const n = norm(name);
  if (/χουμουσ|αρακα|φασολακια/.test(n)) return false;
  if (category === 'Όσπρια') return true;
  if (n === 'φασολαδα') return true;
  return false;
}

