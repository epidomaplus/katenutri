  if (/ψωμ|πιτα|τορτιγ|φρυγαν|παξιμαδ|κριτσιν|κουλουρ|ντακο|τοστ/.test(n)) {
    base[0] = Math.max(base[0], /ολικ|σικαλ|ζεα/.test(n) ? 6 : 2.4);
    base[1] = 470; base[2] = 90; base[3] = 2.3;
  }
  if (/ολικ|βρωμ|κασταν|κινοα|πλιγουρ|κριθαρ|φαγοπυρ/.test(n)) base[0] = Math.max(base[0], 4);
  if (/κορν φλεκ/.test(n)) base[1] = 660;
  if (CHEESE.test(n)) { base[1] = Math.max(base[1], 700); base[2] = Math.max(base[2], 400); }
